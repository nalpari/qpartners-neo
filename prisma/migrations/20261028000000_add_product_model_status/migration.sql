-- 형번 제품상태 컬럼 추가 — 요구사항정의서 v1.1 REQ-005 / REQ-007.
--
-- 배경:
--   제품상태(現行品 / 販売終了品)를 **형번의 속성**으로 둔다. 종전 구현은 콘텐츠의 분류축
--   (카테고리 `PRDST`)으로 갖고 있었는데, 요구사항정의서 v1.1(2026-10-23) REQ-007 이
--   형번 마스터 관리 항목에 제품상태를 명시하고, REQ-005 가 자료일람의 제품상태를
--   「연결된 형번에서 파생」으로 규정했다. 목업 업무리뷰 결정사항(2026-10-20)도 동일하다.
--
--   파생 규칙 (REQ-005):
--     연결 형번 중 하나라도 `current`  → 現行品
--     연결 형번이 전부 `eol`           → 販売終了品
--     연결 형번이 없음                 → 「-」
--
--   이렇게 두면 단종 처리가 형번관리 한 곳으로 모인다. 종전 방식은 자료마다 분류를
--   고쳐야 해서 누락된 자료가 「단종인데 현행품으로 표시」되는 상태로 남았다.
--
-- 기존 행 처리:
--   전부 `current`(現行品)로 채운다. 단종 형번은 운영자가 형번관리 화면에서 개별 지정한다.
--   이행할 원본 데이터가 없다 — 카테고리 `PRDST` 는 **콘텐츠**에 붙어 있고 형번에는
--   붙어 있지 않아, 자료→형번 역방향 추정은 근거가 없다(한 형번이 여러 자료에 연결되고
--   그 자료들의 분류가 서로 다를 수 있다).
--
-- 멱등성:
--   `ADD COLUMN IF NOT EXISTS` — 재적용해도 기존 값을 덮지 않는다.
--   카테고리 `PRDST` 축은 **지우지 않는다.** 화면 노출만 카테고리 관리의 `一覧表示`(is_visible)
--   로 끄고, 붙어 있는 분류 데이터는 보존한다 (2026-10-28 사용자 결정) — 되돌릴 수 있도록.

ALTER TABLE `qp_product_models`
  ADD COLUMN IF NOT EXISTS `status` ENUM('current', 'eol') NOT NULL DEFAULT 'current';

-- 제품일람 정렬(REQ-005: 카테고리 표시순서 → 형번 오름차순)과 제품상태 표시가
-- 같은 조회에서 함께 쓰이므로 복합 인덱스에 얹지 않고 단일로 둔다 —
-- 2값 컬럼이라 선택도가 낮아 단독 인덱스의 이득이 없다. 인덱스는 추가하지 않는다.
